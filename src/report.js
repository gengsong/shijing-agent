/**
 * Turn a run into a Markdown comparison a reviewer can read in a PR comment.
 */
const ICON = { passed: '✅ passed', failed: '❌ failed', error: '⚠️ error' };

// USD per million tokens, for the cost line only. Update when prices change.
const PRICES = {
  'claude-opus-5-5': [4, 20],
  'claude-sonnet-5-5': [2, 10],
  'claude-haiku-5-5': [0.1, 0.5],
};

export function estimateCost(planner, usage) {
  const model = planner?.startsWith('claude:') ? planner.slice(7) : null;
  const price = model && PRICES[model];
  if (!price || !usage) return null;
  return (usage.input_tokens * price[0] + usage.output_tokens * price[1]) / 1e6;
}

const short = (planner) => planner.replace(/^claude:claude-/, '');

/** Planner used for a target: the escalation chain if there was one, plus calls and estimated cost. */
export function plannerCell(r) {
  const attempts = r.attempts ?? [{ planner: r.planner, status: r.status, usage: r.usage }];
  const chain = attempts.length > 1
    ? attempts.map((a) => `${short(a.planner)} (${a.status})`).join(' → ')
    : short(r.planner);
  const calls = attempts.reduce((n, a) => n + (a.usage?.requests ?? 0), 0);
  const costs = attempts.map((a) => estimateCost(a.planner, a.usage));
  const cost = costs.every((c) => c == null) ? null : costs.reduce((t, c) => t + (c ?? 0), 0);
  return `${chain}${calls ? ` · ${calls} calls` : ''}${cost != null ? ` · ~$${cost.toFixed(4)}` : ''}`;
}

export function renderMarkdown(run) {
  const rs = run.results;
  const col = (fn) => rs.map(fn).join(' | ');
  const lines = [];
  lines.push(`## Shijing · ${run.task.name}`, '');
  lines.push(`**Goal:** ${run.task.goal}`, '');
  lines.push(`| | ${col((r) => `\`${r.target}\``)} |`);
  lines.push(`|---|${rs.map(() => '---').join('|')}|`);
  lines.push(`| Result | ${col((r) => ICON[r.status] ?? r.status)} |`);
  lines.push(`| Clicks | ${col((r) => (r.status === 'passed' ? `**${r.clicks}**` : `${r.clicks} (not finished)`))} |`);
  lines.push(`| Path | ${col((r) => r.steps.map((s) => s.label).join(' → ') || '—')} |`);
  lines.push(`| Output | ${col((r) => (r.output ? `\`${r.output.name}\` · ${r.output.bytes} B · sha256 \`${r.output.sha256.slice(0, 12)}\`` : '—'))} |`);
  lines.push(`| Time | ${col((r) => `${r.seconds}s`)} |`);
  if (rs.some((r) => r.usage || r.attempts)) {
    lines.push(`| Planner | ${col(plannerCell)} |`);
  }
  lines.push('');

  const verdict = compare(rs);
  if (verdict) lines.push(`**Verdict:** ${verdict}`, '');

  for (const r of rs) {
    if (r.status !== 'passed') lines.push(`- \`${r.target}\`: ${r.reason}`);
  }
  lines.push('', '<sub>Generated by shijing-agent. Success is decided by independent checks on the real output, not by the agent.</sub>');
  return lines.join('\n') + '\n';
}

/** Compare the first target (baseline) with the last one (candidate). */
export function compare(results) {
  if (results.length < 2) return null;
  const a = results[0];
  const b = results[results.length - 1];
  if (a.status === 'passed' && b.status !== 'passed') return `\`${b.target}\` no longer completes the task (regression).`;
  if (a.status !== 'passed' && b.status === 'passed') return `\`${b.target}\` completes the task; \`${a.target}\` did not.`;
  if (a.status !== 'passed') return 'Neither version completed the task.';
  const same = a.output && b.output ? (a.output.sha256 === b.output.sha256 ? ' with identical output' : ' but the output differs') : '';
  const diff = b.clicks - a.clicks;
  if (diff < 0) return `\`${b.target}\` completes the task in ${b.clicks} click${b.clicks === 1 ? '' : 's'} instead of ${a.clicks} (${diff})${same}.`;
  if (diff > 0) return `\`${b.target}\` needs ${diff} more click${diff === 1 ? '' : 's'} than \`${a.target}\` (${a.clicks} → ${b.clicks})${same}.`;
  return `Same number of clicks (${a.clicks})${same}.`;
}
